"""Build supabase/fixups_text_corrections.sql: typo corrections confirmed by >=2 independent sources and/or the printed page.
Keeps the book's original in hadiths.arabic_printed. Usage: python3 scripts/apply_print_corrections.py  (then run the .sql)"""
import glob, gzip, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARKS = 'ؐ-ًؚ-ٰٟۖ-ۭـ'
H = re.compile('[' + MARKS + ']')
RUN = re.compile('[ء-ي' + MARKS + ']+')
MAP = {'أ': 'ا', 'إ': 'ا', 'آ': 'ا', 'ى': 'ي', 'ة': 'ه', 'ؤ': 'و', 'ئ': 'ي'}


def norm(w):
    w = H.sub('', w)
    for a, b in MAP.items():
        w = w.replace(a, b)
    return re.sub(r'[^ء-ي]', '', w)


def runs(text):
    masked = re.sub(r'\([^)]*\)|\[[^\]]*\]', lambda m: ' ' * len(m.group(0)), text)
    return [(norm(m.group(0)), m.group(0), m.start(), m.end()) for m in RUN.finditer(masked) if norm(m.group(0))]


b = sorted(glob.glob(ROOT + '/backups/*'))[-1]
HD = {h['id']: h for h in json.load(gzip.open(b + '/hadiths.json.gz', 'rt'))}
edits = {}      # id -> [(start, end, new, note)]


def add(i, start, end, new, note):
    edits.setdefault(i, []).append((start, end, new, note))


def token_fix(i, old_norm, new_raw, note, prev=None, nxt=None):
    t = HD[i]['arabic_text']
    r = runs(t)
    hits = [k for k, x in enumerate(r) if x[0] == old_norm and (prev is None or (k > 0 and r[k - 1][0] == prev)) and (nxt is None or (k + 1 < len(r) and r[k + 1][0] == nxt))]
    if len(hits) != 1:
        print('SKIP', i, old_norm, 'occurrences', len(hits))
        return
    add(i, r[hits[0]][2], r[hits[0]][3], new_raw, note)


# 1) "صلى اللهم عليه وسلم" -> "صلى الله ..." (printed typo, 21 hadith) and "الترمدي" -> "الترمذي"
for i, h in HD.items():
    r = runs(h['arabic_text'])
    for k in range(1, len(r) - 1):
        if r[k][0] == 'اللهم' and r[k - 1][0] == 'صلي' and r[k + 1][0] == 'عليه':
            add(i, r[k][2], r[k][3], 'اللَّهُ', 'صلى اللهم -> صلى الله (printed typo; all sources have الله)')
    for x in r:
        if x[0] == 'ترمدي':
            add(i, x[2], x[3], x[1].replace('د', 'ذ'), 'ترمدي -> ترمذي (printed typo)')
# bracketed notes are masked above; handle "ترمدي" inside brackets too
for i, h in HD.items():
    for m in re.finditer(r'ترمدي|التِّرْمِدِي|الترمدي', h['arabic_text']):
        if not any(s <= m.start() < e for s, e, *_ in edits.get(i, [])):
            add(i, m.start(), m.end(), m.group(0).replace('د', 'ذ').replace('مِدِي', 'مِذِي'), 'ترمدي -> ترمذي (printed typo)')

# 2) typos where sunnah dataset + an OpenITI edition agree (scripts/propose_corrections.py, reviewed by hand)
token_fix(3882, 'ني', 'إِنِّي', 'missing إ (3 sources)')
token_fix(13101, 'قالو', 'قَالُوا', 'missing final alif (3 sources)')
token_fix(16383, 'نواجده', 'نَوَاجِذُهُ', 'ذ not د (3 sources; also confirmed on the print as a printed typo)')
token_fix(12965, 'وغربت', 'وَجَبَتِ', 'وجبت (3 sources)')
token_fix(16256, 'يدعوا', 'يَدْعُو', 'extra alif (2 sources)')
token_fix(16595, 'يدعوا', 'يَدْعُو', 'extra alif (2 sources)')
token_fix(17027, 'المليكه', 'الْمَلَائِكَةَ', 'ملائكة spelling (3 sources)')

# 3) OCR errors found by comparing with the printed page (vol 2), print and collections agree
token_fix(4605, 'صيبا', 'سَيْبًا', 'OCR: print سيبا')
token_fix(3921, 'مرجل', 'مُرَحَّلٌ', 'OCR: print مرحل')
token_fix(3890, 'الابجر', 'الْأَبَحِّ', 'OCR: print الأبح')
token_fix(3890, 'السليعي', 'السَّلِيحِيِّ', 'OCR: print السليحي')
token_fix(3278, 'ليورثه', 'لَيُوَرِّثَنَّهُ', 'OCR: print ليورثنه')
token_fix(3291, 'للفحتك', 'لَلَفَعَتْكَ', 'OCR: print للفعتك')
token_fix(2473, 'الهاني', 'أَلْهَانِي', 'OCR: print ألهاني (ya)')
token_fix(3913, 'بضعه', 'بِبِضْعَةَ', 'OCR: print ببضعة (matches collections)')
token_fix(51, 'تقدموا', 'تَتَقَدَّمُوا', 'OCR: print تتقدموا (matches collections)')
token_fix(2831, 'تكلم', 'يُكَلِّمَ', 'OCR: print يكلم (matches collections)')
token_fix(3382, 'فقيل', 'فَقَالَ', 'OCR: print فقال', nxt='لي')

sql = ["-- Typo corrections (2026-10-11). Originals kept in hadiths.arabic_printed. Generated by scripts/apply_print_corrections.py",
       "alter table hadiths add column if not exists arabic_printed text;",
       "alter table hadiths add column if not exists correction_note text;"]
log = []
for i, es in sorted(edits.items()):
    t = HD[i]['arabic_text']
    new = t
    for s, e, rep, note in sorted(es, reverse=True):
        new = new[:s] + rep + new[e:]
    notes = '; '.join(sorted({n for *_, n in es}))
    sql.append(f"update hadiths set arabic_printed = coalesce(arabic_printed, arabic_text), arabic_text = $n${new}$n$, correction_note = $c${notes}$c$ where id = {i} and arabic_text = $o${t}$o$;")
    log.append({'id': i, 'edits': [{'old': t[s:e], 'new': rep, 'note': note} for s, e, rep, note in sorted(es)]})
open(os.path.join(ROOT, 'supabase/fixups_text_corrections.sql'), 'w').write('\n'.join(sql) + '\n')
json.dump(log, open(os.path.join(ROOT, 'data/verify/corrections_applied.json'), 'w'), ensure_ascii=False, indent=1)
print('hadith to update', len(edits), 'edits', sum(len(v) for v in edits.values()))
