"""Merge prose page JSON (ocr/v1/art/{intro,article,author}) into supabase/seed_articles.sql.
usage: python3 -I scripts/build_articles.py
Sections are cut at `heading` blocks and matched in order to index sections 1..7 + 32 (ocr/v1/index.json)."""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
idx = json.load(open(os.path.join(ROOT, 'ocr/v1/index.json'), encoding='utf-8'))
prose = [s for s in idx['sections'] if s['no'] <= 7 or s['no'] == 32]   # 32 = about the author (1.28.pdf)


def norm_ml(t):
    return (t.replace('ളള', 'ള്ള').replace('ൻമ', 'ന്മ')
             .replace('ഈൗ', 'ഈ').replace('ഇൗ', 'ഈ').replace('ഒൗ', 'ഔ')
             .replace('ഉൗ', 'ഊ').replace('ററ', 'റ്റ'))


pages = []
for src in ('intro', 'article', 'author'):
    for f in sorted(glob.glob(os.path.join(ROOT, 'ocr/v1/art', src, 'p*.json'))):
        pages.append(json.load(open(f, encoding='utf-8')))
blocks = []   # (kind, text, rows, printed_page)
midword = False
for p in pages:
    pg = p.get('printed_page')
    for bi, b in enumerate(p['blocks']):
        t = b['type']
        txt = b.get('text')
        if txt is not None and t != 'arabic':
            txt = norm_ml(txt)
        if (bi == 0 and p.get('starts_mid_word') and blocks and blocks[-1][0] == 'paragraph' and t == 'paragraph'):
            blocks[-1] = ('paragraph', blocks[-1][1] + txt.strip(), None, blocks[-1][3])
        elif bi == 0 and t == 'paragraph' and blocks and blocks[-1][0] == 'paragraph' and blocks[-1][3] != pg \
                and not re.search(r'[.!?”"\)]\s*$', blocks[-1][1]):
            blocks[-1] = ('paragraph', blocks[-1][1] + ' ' + txt.strip(), None, blocks[-1][3])
        else:
            blocks.append((t, txt, b.get('rows'), pg))

# cut sections at headings
secs, cur = [], None
for b in blocks:
    if b[0] == 'heading':
        cur = {'title': b[1].strip(), 'page': b[3], 'blocks': []}
        secs.append(cur)
    elif cur is None:
        cur = {'title': prose[0]['title_ml'], 'page': b[3], 'blocks': [b]}
        secs.append(cur)
    else:
        cur['blocks'].append(b)
report = [f'{len(secs)} sections found, index has {len(prose)}']
for i, s in enumerate(secs):
    ref = prose[i] if i < len(prose) else None
    report.append(f'  {i + 1}: "{s["title"]}" p{s["page"]} blocks={len(s["blocks"])} | index: {ref and ref["title_ml"]} p{ref and ref["page"]}')


def q(v):
    return 'null' if v is None else "'" + str(v).replace("'", "''") + "'"


out = ['-- generated by scripts/build_articles.py', 'begin;',
       "insert into volumes (id, title_ml) values (1, 'വാല്യം 1') on conflict (id) do nothing;",
       'delete from articles where volume_id = 1;']
for i, s in enumerate(secs):
    ref = prose[i] if i < len(prose) else {'no': i + 1, 'title_ml': s['title'], 'page': s['page']}
    end = max([b[3] or 0 for b in s['blocks']] + [s['page'] or 0])
    out.append(f"insert into articles (volume_id, section_no, title_ml, start_page, end_page) values (1, {ref['no']}, "
               f"{q(ref['title_ml'].rstrip(':'))}, {q(ref['page'])}, {q(end)});")
    for n, b in enumerate(s['blocks'], 1):
        rows = "'" + json.dumps(b[2], ensure_ascii=False).replace("'", "''") + "'::jsonb" if b[2] else 'null'
        out.append(f"insert into article_blocks (article_id, seq, kind, text_ml, rows, page) select id, {n}, {q(b[0])}, "
                   f"{q(b[1])}, {rows}, {q(b[3])} from articles where volume_id=1 and section_no={ref['no']};")
out.append('commit;')
open(os.path.join(ROOT, 'supabase/seed_articles.sql'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
os.makedirs(os.path.join(ROOT, 'data/articles'), exist_ok=True)
open(os.path.join(ROOT, 'data/articles/report.txt'), 'w', encoding='utf-8').write('\n'.join(report) + '\n')
print('\n'.join(report))
