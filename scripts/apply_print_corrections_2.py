"""Build supabase/fixups_text_corrections.sql: typo corrections confirmed by >=2 independent sources and/or the printed page.
Keeps the book's original in hadiths.arabic_printed. Usage: python3 scripts/apply_print_corrections.py  (then run the .sql)"""
import glob, gzip, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MARKS = 'ؐ-ًؚ-ٰٟۖ-ۭـ'
H = re.compile('[' + MARKS + ']')
RUN = re.compile('[ء-ي' + MARKS + ']+')
MAP = {'أ': 'ا', 'إ': 'ا', 'آ': 'ا', 'ى': 'ي', 'ة': 'ه', 'ؤ': 'و', 'ئ': 'ي'}


def norm(w):
    w = H.sub('', w)
    for a, b in MAP.items():
        w = w.replace(a, b)
    return re.sub(r'[^ء-ي]', '', w)


def runs(text):
    masked = re.sub(r'\([^)]*\)|\[[^\]]*\]', lambda m: ' ' * len(m.group(0)), text)
    return [(norm(m.group(0)), m.group(0), m.start(), m.end()) for m in RUN.finditer(masked) if norm(m.group(0))]


b = sorted(glob.glob(ROOT + '/backups/*'))[-1]
HD = {h['id']: h for h in json.load(gzip.open(b + '/hadiths.json.gz', 'rt'))}
edits = {}      # id -> [(start, end, new, note)]


def add(i, start, end, new, note):
    edits.setdefault(i, []).append((start, end, new, note))


def token_fix(i, old_norm, new_raw, note, prev=None, nxt=None):
    t = HD[i]['arabic_text']
    r = runs(t)
    hits = [k for k, x in enumerate(r) if x[0] == old_norm and (prev is None or (k > 0 and r[k - 1][0] == prev)) and (nxt is None or (k + 1 < len(r) and r[k + 1][0] == nxt))]
    if len(hits) != 1:
        print('SKIP', i, old_norm, 'occurrences', len(hits))
        return
    add(i, r[hits[0]][2], r[hits[0]][3], new_raw, note)



# round 2 (parts 1.4-1.11 + continuation pages), print and collections agree
token_fix(13263, 'رويه', 'رِوَايَةٍ', 'OCR: missing alef in رواية (print)')
token_fix(11969, 'فقلنا', 'قُلْنَا', 'OCR: print has no initial فـ (matches collections)', nxt='ويحكم')
t = HD[3565]['arabic_text']
r = runs(t)
for k in range(len(r) - 1):
    if r[k][0] == 'فنظر' and r[k + 1][0] == 'فنظر':
        add(3565, r[k][3], r[k + 1][3], '', 'OCR: duplicated word فنظر (print has it once)')

sql = ["-- Typo corrections (2026-10-11). Originals kept in hadiths.arabic_printed. Generated by scripts/apply_print_corrections.py",
       "alter table hadiths add column if not exists arabic_printed text;",
       "alter table hadiths add column if not exists correction_note text;"]
log = []
for i, es in sorted(edits.items()):
    t = HD[i]['arabic_text']
    new = t
    for s, e, rep, note in sorted(es, reverse=True):
        new = new[:s] + rep + new[e:]
    notes = '; '.join(sorted({n for *_, n in es}))
    sql.append(f"update hadiths set arabic_printed = coalesce(arabic_printed, arabic_text), arabic_text = $n${new}$n$, correction_note = $c${notes}$c$ where id = {i} and arabic_text = $o${t}$o$;")
    log.append({'id': i, 'edits': [{'old': t[s:e], 'new': rep, 'note': note} for s, e, rep, note in sorted(es)]})
open(os.path.join(ROOT, 'supabase/fixups_text_corrections_2.sql'), 'w').write('\n'.join(sql) + '\n')
json.dump(log, open(os.path.join(ROOT, 'data/verify/corrections_applied_2.json'), 'w'), ensure_ascii=False, indent=1)
print('hadith to update', len(edits), 'edits', sum(len(v) for v in edits.values()))
