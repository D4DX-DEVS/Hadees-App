"""Vol 2 prose (src_v2/introduction.pdf, index book 1 "ആമുഖമായി", printed pp.47-48) -> supabase/seed_articles_v2.sql
(articles + article_blocks, volume 2). Page JSON: ocr/v2/art/intro/pNNN.json (same format as ocr/ARTICLES_V1.md).
usage: python3 -I scripts/build_articles_v2.py"""
import glob, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = os.path.join(ROOT, 'ocr/v2/art/intro')
SENTENCE_END = ('.', '!', '?', ':', '"', "'", ')')

blocks = []  # (type, text, rows, printed_page)
for f in sorted(glob.glob(os.path.join(PAGES, 'p*.json'))):
    p = json.load(open(f, encoding='utf-8'))
    pg = p['printed_page']
    for bi, b in enumerate(p['blocks']):
        txt = (b.get('text') or '').strip()
        prev = blocks[-1] if blocks else None
        # a paragraph cut by the page break continues as the first block of the next page
        if bi == 0 and prev and prev[0] == 'paragraph' and b['type'] == 'paragraph' and \
                (p.get('starts_mid_word') or not prev[1].endswith(SENTENCE_END)):
            sep = '' if p.get('starts_mid_word') else ' '
            blocks[-1] = ('paragraph', prev[1] + sep + txt, None, prev[3])
        else:
            blocks.append((b['type'], txt, b.get('rows'), pg))

secs = []
for t, txt, rows, pg in blocks:
    if t == 'heading':
        secs.append({'title': txt.rstrip(':'), 'page': pg, 'blocks': []})
        continue
    if not secs:
        raise SystemExit('first block is not a heading')
    secs[-1]['blocks'].append((t, txt, rows, pg))


def q(v):
    return 'null' if v is None else "'" + str(v).replace("'", "''") + "'"


out = ['-- generated by scripts/build_articles_v2.py', 'begin;',
       "insert into volumes (id, title_ml) values (2, 'വാല്യം 2') on conflict (id) do nothing;",
       'delete from articles where volume_id = 2;']
for i, s in enumerate(secs, 1):
    end = max([x[3] for x in s['blocks']] + [s['page']])
    out.append(f"insert into articles (volume_id, section_no, title_ml, start_page, end_page) "
               f"values (2, {i}, {q(s['title'])}, {q(s['page'])}, {q(end)});")
    for n, (t, txt, rows, pg) in enumerate(s['blocks'], 1):
        r = q(json.dumps(rows, ensure_ascii=False)) if rows else 'null'
        out.append(f"insert into article_blocks (article_id, seq, kind, text_ml, rows, page) select id, {n}, {q(t)}, "
                   f"{q(txt or None)}, {r}, {q(pg)} from articles where volume_id=2 and section_no={i};")
out.append('commit;')
open(os.path.join(ROOT, 'supabase/seed_articles_v2.sql'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('sections', len(secs), [(s['title'], s['page'], len(s['blocks'])) for s in secs])
