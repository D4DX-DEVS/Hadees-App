"""Group the ~2,000 printed spellings of narrator names into people.
Reads distinct narrator_ml from the live DB (supabase CLI), writes supabase/narrator_groups.sql.
Rules: (1) fold spaces / ZWNJ / "(റ)" / ibn spelling variants, (2) curated regexes for the well-known companions
whose name is printed several ways (Abu Hurairah/Abu Huraira, Ibn Abbas/Abdullah ibn Abbas ...).
Chains such as "A, B" are never merged. Usage: python3 scripts/build_narrator_groups.py"""
import collections, json, re, subprocess, sys

ROOT = __file__.rsplit('/scripts/', 1)[0]
out = subprocess.run(['supabase', 'db', 'query', '--linked', '-o', 'json',
                      'select narrator_ml n, count(*) c from hadiths where narrator_ml is not null group by 1'],
                     capture_output=True, text=True, cwd=ROOT).stdout
rows = json.loads(out[out.index('{'):])['rows']


def fold(s):
    s = re.sub(r'\(.*?\)|[()]', '', s).replace('‌', '').replace('‍', '')
    s = re.sub(r'\s+', '', s)
    # inner "son of" variants -> ബ്നു (not at the very start: "ഇബ്നു..." is a name by itself)
    s = re.sub(r'(?<=.)(ഇബ്നു|ഇബനു|ബിൻ|ബിനു|ബുനു)', 'ബ്നു', s)
    s = re.sub(r'ത്ത?്?ു?ബ്നു', 'തുബ്നു', s)             # ...ത്തുബ്നു / ...ത്ബ്നു / ...തുബ്നു
    return s


# (label key, regex on the folded name)
