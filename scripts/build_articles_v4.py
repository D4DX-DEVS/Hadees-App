"""Vol 4 intro (prose) -> articles rows for volume 4. Applies ocr/v4/art/intro_corr/adj_V1.json to ocr/v4/art/intro pages,
cuts sections at heading blocks, writes supabase/seed_articles_v4.sql. usage: python3 -I scripts/build_articles_v4.py"""
import glob, json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = os.path.join(ROOT, 'ocr/v4/art/intro')
# apply intro corrections (exact substring, once per block)
corr = json.load(open(os.path.join(ROOT, 'ocr/v4/art/intro_corr/adj_V1.json'), encoding='utf-8'))
applied = 0
for x in corr.get('corrections', []):
    f = os.path.join(PAGES, f"p{x['pdf_page']:03d}.json")
    pg = json.load(open(f, encoding='utf-8'))
    b = pg['blocks'][x['block']]
    if b.get('text', '').count(x['old']) == 1:
        b['text'] = b['text'].replace(x['old'], x['new'], 1); applied += 1
        json.dump(pg, open(f, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('intro corrections applied', applied, 'of', len(corr.get('corrections', [])))
blocks = []
for p in sorted(glob.glob(os.path.join(PAGES, 'p*.json'))):
    pg = json.load(open(p, encoding='utf-8'))
    for b in pg['blocks']:
        blocks.append((b['type'], (b.get('text') or '').strip(), pg['printed_page']))
secs = []
for t, txt, pgn in blocks:
    if t == 'heading' or not secs:
        secs.append({'title': txt if t == 'heading' else 'ആമുഖം', 'page': pgn, 'blocks': []})
        if t == 'heading': continue
    secs[-1]['blocks'].append((t, txt, pgn))
def q(v): return 'null' if v is None else "'" + str(v).replace("'", "''") + "'"
out = ["-- generated by scripts/build_articles_v4.py", 'begin;',
       "insert into volumes (id, title_ml) values (4, 'വാല്യം 4') on conflict (id) do nothing;",
       'delete from articles where volume_id = 4;']
for i, s in enumerate(secs, 1):
    end = max([x[2] for x in s['blocks']] + [s['page']])
    out.append(f"insert into articles (volume_id, section_no, title_ml, start_page, end_page) values (4, {i}, {q(s['title'].rstrip(':'))}, {q(s['page'])}, {q(end)});")
    for n, (t, txt, pgn) in enumerate(s['blocks'], 1):
        out.append(f"insert into article_blocks (article_id, seq, kind, text_ml, rows, page) select id, {n}, {q(t)}, {q(txt)}, null, {q(pgn)} from articles where volume_id=4 and section_no={i};")
out.append('commit;')
open(os.path.join(ROOT, 'supabase/seed_articles_v4.sql'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('sections', len(secs), [s['title'][:30] for s in secs])
