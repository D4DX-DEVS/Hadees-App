"""Convert a SQLite source library (sunnah.db / ihadis.db) into a PostgreSQL bundle for cPanel. Stdlib only.

  python -I scripts/build_sources_db.py sunnah  [--db PATH] [--with-html]
  python -I scripts/build_sources_db.py ihadis  [--db PATH]

Output: sources-bundle/<name>/ and <name>-bundle.zip (a loadable folder, same loader as db-bundle):
  00_schema.sql      DROP + CREATE SCHEMA <name> (only that schema, never `public`), tables, primary keys
  10_data_*.sql      COPY ... FROM STDIN chunks (each file one statement: safe to re-run after a failure)
  80_indexes.sql     lookup indexes, built after the data
  90_grants.sql      read-only access for the API user (hadithencyclo_api)
  99_verify.sql      row counts + character sums per table;   99_expected.txt = the same figures from the SQLite file
  load.sh            the loader (copy of scripts/cpanel_load.sh)

The live library in schema `public` is never touched. Bookkeeping tables of the scrapers are not exported.
arabic_html / english_html (the same text wrapped in tags, ~130 MB) are left out unless --with-html is given."""
import os, re, shutil, sqlite3, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_DB = {'sunnah': r'D:\Projects\sunnah\sunnah.db', 'ihadis': r'D:\Projects\sunnah\ihadis.db'}
SKIP_TABLES = {'fetch_log', 'log', 'sqlite_sequence', 'extra_values', 'field_config', 'migrated_translations'}
HTML_COLS = {'arabic_html', 'english_html'}
INDEXES = {
    'sunnah': [('hadiths', 'collection, book_number'), ('hadiths', 'collection, hadith_number'),
               ('topic_hadiths', 'urn'), ('translations', 'lang')],
    'ihadis': [('hadiths', 'book_slug, chapter_id'), ('hadiths', 'sunnah_ref'), ('topic_hadiths', 'book_slug, hadith_id')],
}
CHUNK_BYTES = 8 * 1024 * 1024
API_USER = 'hadithencyclo_api'

args = [a for a in sys.argv[1:] if not a.startswith('--')]
if not args or args[0] not in DEFAULT_DB:
    sys.exit(__doc__)
NAME = args[0]
WITH_HTML = '--with-html' in sys.argv
DB = DEFAULT_DB[NAME]
if '--db' in sys.argv:
    DB = sys.argv[sys.argv.index('--db') + 1]
OUT = os.path.join(ROOT, 'sources-bundle', NAME)
ZIP = os.path.join(ROOT, f'{NAME}-bundle.zip')

con = sqlite3.connect(f'file:{DB}?mode=ro', uri=True)
tables = [r[0] for r in con.execute("select name from sqlite_master where type='table' order by name") if r[0] not in SKIP_TABLES]


def q(ident):
    return '"' + ident.replace('"', '""') + '"'


def columns(table):
    """[(name, 'integer'|'text', pk_position)] without the HTML columns."""
    cols = []
    for _, name, typ, _, _, pk in con.execute(f'pragma table_info({q(table)})'):
        if not WITH_HTML and name in HTML_COLS:
            continue
        cols.append((name, 'integer' if 'INT' in (typ or '').upper() else 'text', pk))
    return cols


def esc(v):
    if v is None:
        return '\\N'
    return v.replace('\\', '\\\\').replace('\t', '\\t').replace('\n', '\\n').replace('\r', '\\r')


if os.path.isdir(OUT):
    shutil.rmtree(OUT)
os.makedirs(OUT)


def write(name, text):
    with open(os.path.join(OUT, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


ddl = [f'-- {NAME}: generated by scripts/build_sources_db.py from {os.path.basename(DB)}',
       f'drop schema if exists {NAME} cascade;', f'create schema {NAME};']
expected, verify = [], []
nuls = 0
for t in tables:
    cols = columns(t)
    pk = [c[0] for c in sorted((c for c in cols if c[2]), key=lambda c: c[2])]
    body = ',\n  '.join(f'{q(n)} {ty}' + (' not null' if n in pk else '') for n, ty, _ in cols)
    if pk:
        body += f',\n  primary key ({", ".join(q(p) for p in pk)})'
    ddl.append(f'create table {NAME}.{q(t)} (\n  {body}\n);')

    names = [c[0] for c in cols]
    kinds = [c[1] for c in cols]
    cur = con.execute(f'select {", ".join(q(n) for n in names)} from {q(t)}' + (f' order by {", ".join(q(p) for p in pk)}' if pk else ''))
    head = f'copy {NAME}.{q(t)} ({", ".join(q(n) for n in names)}) from stdin;\n'
    part, buf, size, rows = 0, [], 0, 0

    def flush():
        global part, buf, size
        if buf:
            part += 1
            write(f'10_data_{t}_{part:03d}.sql', head + ''.join(buf) + '\\.\n')
            buf, size = [], 0

    for row in cur:
        out = []
        for v, kind, n in zip(row, kinds, names):
            if v is None:
                out.append(None)
            elif kind == 'integer':
                out.append(str(int(v)))
            else:
                s = v if isinstance(v, str) else str(v)
                if '\x00' in s:
                    nuls += 1
                    s = s.replace('\x00', '')
                out.append(s)
        for p in pk:
            if out[names.index(p)] is None:
                sys.exit(f'NULL in primary key {t}.{p}')
        line = '\t'.join(esc(x) for x in out) + '\n'
        buf.append(line)
        size += len(line)
        rows += 1
        if size >= CHUNK_BYTES:
            flush()
    flush()

    text_cols = [n for n, ty, _ in cols if ty == 'text']
    if text_cols:
        chars_pg = ' + '.join(f'coalesce(length({q(n)}),0)' for n in text_cols)
        chars_lite = chars_pg
    else:
        chars_pg = chars_lite = '0'
    nrows = con.execute(f'select count(*) from {q(t)}').fetchone()[0]
    if nrows != rows:
        sys.exit(f'{t}: read {rows} rows but count is {nrows}')
    chars = con.execute(f'select coalesce(sum({chars_lite}),0) from {q(t)}').fetchone()[0]
    label = f'{NAME}.{t}'
    expected.append(f'{label} rows={nrows} chars={chars}')
    verify.append(f"select '{label} rows=' || count(*) || ' chars=' || coalesce(sum({chars_pg}),0) as line from {NAME}.{q(t)}")
    print(f'{label:34s} {nrows:>8} rows  {part} file(s)', flush=True)

write('00_schema.sql', '\n'.join(ddl) + '\n')
idx = [f'create index if not exists {NAME}_{t}_{re.sub(r"[^a-z0-9]+", "_", c.lower()).strip("_")}_idx on {NAME}.{q(t)} ({c});'
       for t, c in INDEXES[NAME] if t in tables]
write('80_indexes.sql', '\n'.join(idx + [f'analyze;']) + '\n')
write('90_grants.sql', '\n'.join([
    f'grant usage on schema {NAME} to {API_USER};',
    f'grant select on all tables in schema {NAME} to {API_USER};',
    f'alter default privileges in schema {NAME} grant select on tables to {API_USER};']) + '\n')
write('99_verify.sql', '\nunion all\n'.join(verify) + '\norder by 1;\n')
write('99_expected.txt', '\n'.join(sorted(expected)) + '\n')
shutil.copy(os.path.join(ROOT, 'scripts', 'cpanel_load.sh'), os.path.join(OUT, 'load.sh'))

with zipfile.ZipFile(ZIP, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    for f in sorted(os.listdir(OUT)):
        info = zipfile.ZipInfo(f'{NAME}-bundle/{f}', date_time=(2026, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = (0o755 if f == 'load.sh' else 0o644) << 16
        with open(os.path.join(OUT, f), 'rb') as fh:
            z.writestr(info, fh.read(), compresslevel=9)
print(f'\nwrote {ZIP}: {os.path.getsize(ZIP) // 1024 // 1024} MB, {len(os.listdir(OUT))} files; NUL chars removed: {nuls}')
