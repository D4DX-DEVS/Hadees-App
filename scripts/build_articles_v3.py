"""Vol 3 prose (introduction, index section 1) -> supabase/seed_articles_v3.sql (articles + article_blocks, volume 3).
usage: python3 -I scripts/build_articles_v3.py"""
import glob, json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
idx = json.load(open(os.path.join(ROOT, 'ocr/v3/index.json'), encoding='utf-8'))
sec = next(s for s in idx['sections'] if s['no'] == 1)


def norm_ml(t):
    return (t.replace('ളള', 'ള്ള').replace('ൻമ', 'ന്മ').replace('ഈൗ', 'ഈ').replace('ഇൗ', 'ഈ')
             .replace('ഒൗ', 'ഔ').replace('ഉൗ', 'ഊ').replace('ററ', 'റ്റ')
             .replace('ൊ', 'ൊ').replace('ോ', 'ോ'))


blocks = []
for f in sorted(glob.glob(os.path.join(ROOT, 'ocr/v3/art/intro/p*.json'))):
    p = json.load(open(f, encoding='utf-8'))
    pg = p.get('printed_page')
    for bi, b in enumerate(p['blocks']):
        txt = b.get('text')
        if txt is not None and b['type'] != 'arabic':
            txt = norm_ml(txt)
        if bi == 0 and p.get('starts_mid_word') and blocks and blocks[-1][0] == 'paragraph' and b['type'] == 'paragraph':
            blocks[-1] = ('paragraph', blocks[-1][1] + txt.strip(), None, blocks[-1][3])
        else:
            blocks.append((b['type'], txt, b.get('rows'), pg))


def q(v):
    return 'null' if v is None else "'" + str(v).replace("'", "''") + "'"


end = max(b[3] or 0 for b in blocks)
out = ['-- generated by scripts/build_articles_v3.py', 'begin;',
       "insert into volumes (id, title_ml) values (3, 'വാല്യം 3') on conflict (id) do nothing;",
       'delete from articles where volume_id = 3 and section_no = 1;',
       f"insert into articles (volume_id, section_no, title_ml, start_page, end_page) values (3, 1, {q(sec['title_ml'])}, {q(sec['page'])}, {q(end)});"]
for n, b in enumerate(blocks, 1):
    out.append(f"insert into article_blocks (article_id, seq, kind, text_ml, rows, page) select id, {n}, {q(b[0])}, {q(b[1])}, null, {q(b[3])} "
               f"from articles where volume_id=3 and section_no=1;")
out.append('commit;')
open(os.path.join(ROOT, 'supabase/seed_articles_v3.sql'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(blocks), 'blocks, pages', sec['page'], '-', end)
